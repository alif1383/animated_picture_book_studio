/** Builds a crisp stepped visibility toggle track at the Zone A → Zone B location cut. */
function zoneToggleTrack(
  nodeId: string,
  cutTime: number,
  showInZoneA: boolean
): TimelineTrack {
  return {
    nodeId,
    keyframes: [
      { time: 0, visible: showInZoneA, hold: true },
      { time: cutTime, visible: !showInZoneA, hold: true },
    ],
  };
}

